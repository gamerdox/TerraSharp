    def dispatch_alert(
        self,
        alert_id: str,
        location_name: str,
        coordinates: Dict[str, float],
        hazard_type: HazardType,
        alert_state: AlertState,
        risk_score: float,
        factors: Optional[ContributingFactors] = None,
        estimated_lead_time_hours: Optional[float] = None,
        recommended_action: str = "",
        confidence_score: float = 1.0,
        data_freshness: str = "FRESH",
        recipients: Optional[List[str]] = None,
        is_test: bool = False,
    ) -> List[EmailDispatchRecord]:
        """
        Dispatches emergency email alerts to all configured recipients.
        Falls back to SIMULATED if SMTP credentials are not configured.
        """
        target_recipients = recipients or settings.alert_recipient_emails
        if not target_recipients:
            target_recipients = ["disaster-response@kerala.gov.in"]

        subject, text_body, html_body = self.format_email_content(
            alert_id=alert_id,
            location_name=location_name,
            coordinates=coordinates,
            hazard_type=hazard_type,
            alert_state=alert_state,
            risk_score=risk_score,
            factors=factors,
            estimated_lead_time_hours=estimated_lead_time_hours,
            recommended_action=recommended_action,
            confidence_score=confidence_score,
            data_freshness=data_freshness,
            is_test=is_test,
        )

        smtp_ready = self.is_smtp_configured()
        dispatched_records: List[EmailDispatchRecord] = []

        for recipient in target_recipients:
            dispatch_id = f"DSP-{uuid.uuid4().hex[:8].upper()}"

            if not smtp_ready:
                # Honest simulation: Explicitly tag as SIMULATED
                rec = EmailDispatchRecord(
                    dispatch_id=dispatch_id,
                    alert_id=alert_id,
                    village_name=location_name,
                    severity=alert_state,
                    hazard_type=hazard_type,
                    recipient=recipient,
                    subject=subject,
                    status=EmailStatus.SIMULATED,
                    timestamp=datetime.now(timezone.utc),
                    error_message="SMTP not configured in .env (Running in simulated notification mode)",
                    retry_count=0,
                    simulated=True,
                )
                self.dispatch_records.append(rec)
                dispatched_records.append(rec)
                logger.info(f"[SIMULATED EMAIL] Alert {alert_id} for {location_name} logged for {recipient}")
                continue

            # Real SMTP Attempt
            try:
                msg = MIMEMultipart("alternative")
                msg["Subject"] = subject
                msg["From"] = settings.smtp_from
                msg["To"] = recipient

                msg.attach(MIMEText(text_body, "plain"))
                msg.attach(MIMEText(html_body, "html"))

                with smtplib.SMTP(settings.smtp_host, settings.smtp_port, timeout=settings.smtp_timeout_seconds) as server:
                    if settings.smtp_use_tls:
                        server.starttls()
                    if settings.smtp_user and settings.smtp_password:
                        server.login(settings.smtp_user, settings.smtp_password)
                    server.send_message(msg)

                rec = EmailDispatchRecord(
                    dispatch_id=dispatch_id,
                    alert_id=alert_id,
                    village_name=location_name,
                    severity=alert_state,
                    hazard_type=hazard_type,
                    recipient=recipient,
                    subject=subject,
                    status=EmailStatus.SENT,
                    timestamp=datetime.now(timezone.utc),
                    error_message=None,
                    retry_count=0,
                    simulated=False,
                )
                logger.info(f"[REAL EMAIL SENT] Alert {alert_id} delivered to {recipient} via {settings.smtp_host}")
            except Exception as e:
                logger.error(f"[EMAIL FAILED] Failed to send alert {alert_id} to {recipient}: {e}")
                rec = EmailDispatchRecord(
                    dispatch_id=dispatch_id,
                    alert_id=alert_id,
                    village_name=location_name,
                    severity=alert_state,
                    hazard_type=hazard_type,
                    recipient=recipient,
                    subject=subject,
                    status=EmailStatus.FAILED,
                    timestamp=datetime.now(timezone.utc),
                    error_message=str(e),
                    retry_count=0,
                    simulated=False,
                )

            self.dispatch_records.append(rec)
            dispatched_records.append(rec)

        return dispatched_records

