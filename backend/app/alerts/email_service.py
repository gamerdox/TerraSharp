    def dispatch_dangerzone_alert(
        self,
        recipient_email: str,
        zone: str,
        lat: float,
        lon: float,
        location_name: str,
        point_data: Dict[str, Any],
        dispatch_reason: str,
        is_test: bool = False,
    ) -> List[EmailDispatchRecord]:
        """
        Dispatches a dangerzone alert to the user's personal email.
        """
        alert_id = f"DZ-{uuid.uuid4().hex[:8].upper()}"
        subject, text_body, html_body = self.format_dangerzone_email(
            alert_id=alert_id,
            zone=zone,
            lat=lat,
            lon=lon,
            location_name=location_name,
            point_data=point_data,
            dispatch_reason=dispatch_reason,
            is_test=is_test,
        )

        dispatch_id = f"DSP-{uuid.uuid4().hex[:8].upper()}"
        severity_state = AlertState.CRITICAL if zone == "RED" else AlertState.WARNING
        hazard_type = HazardType.MULTI_HAZARD

        if not self.is_smtp_configured():
            # Honest simulation
            rec = EmailDispatchRecord(
                dispatch_id=dispatch_id,
                alert_id=alert_id,
                village_name=location_name,
                severity=severity_state,
                hazard_type=hazard_type,
                recipient=recipient_email,
                subject=subject,
                status=EmailStatus.SIMULATED,
                timestamp=datetime.now(timezone.utc),
                error_message="SMTP credentials not configured in backend .env",
                retry_count=0,
                simulated=True,
            )
            self.dispatch_records.append(rec)
            logger.info(f"[SIMULATED DANGERZONE EMAIL] {zone} zone alert logged for {recipient_email}")
            return [rec]

        try:
            msg = MIMEMultipart("alternative")
            msg["Subject"] = subject
            msg["From"] = settings.smtp_from
            msg["To"] = recipient_email

            msg.attach(MIMEText(text_body, "plain"))
            msg.attach(MIMEText(html_body, "html"))

            with smtplib.SMTP(settings.smtp_host, settings.smtp_port, timeout=settings.smtp_timeout_seconds) as server:
                if settings.smtp_use_tls:
                    server.starttls()
                if settings.smtp_user and settings.smtp_password:
                    server.login(settings.smtp_user, settings.smtp_password)
                server.send_message(msg)

            rec = EmailDispatchRecord(
                dispatch_id=dispatch_id,
                alert_id=alert_id,
                village_name=location_name,
                severity=severity_state,
                hazard_type=hazard_type,
                recipient=recipient_email,
                subject=subject,
                status=EmailStatus.SENT,
                timestamp=datetime.now(timezone.utc),
                error_message=None,
                retry_count=0,
                simulated=False,
            )
            logger.info(f"[REAL DANGERZONE EMAIL DELIVERED] Sent to {recipient_email} via {settings.smtp_host}")
        except Exception as e:
            logger.error(f"[EMAIL FAILED] Failed to send dangerzone alert to {recipient_email}: {e}")
            rec = EmailDispatchRecord(
                dispatch_id=dispatch_id,
                alert_id=alert_id,
                village_name=location_name,
                severity=severity_state,
                hazard_type=hazard_type,
                recipient=recipient_email,
                subject=subject,
                status=EmailStatus.FAILED,
                timestamp=datetime.now(timezone.utc),
                error_message=str(e),
                retry_count=0,
                simulated=False,
            )

        self.dispatch_records.append(rec)
        return [rec]

